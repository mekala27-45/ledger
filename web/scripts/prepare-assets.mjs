// Copies what the site serves as static files and cannot import: the DuckDB-WASM
// bundles (self hosted, never from a CDN) and New Jersey's counties from us-atlas.
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { feature } from "topojson-client";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pub = join(root, "public");
const duck = join(root, "node_modules", "@duckdb", "duckdb-wasm", "dist");
mkdirSync(join(pub, "duckdb"), { recursive: true });
// Only the exception handling build: every browser the site supports runs it, and it halves the payload.
for (const file of ["duckdb-eh.wasm", "duckdb-browser-eh.worker.js"]) {
  if (existsSync(join(duck, file))) copyFileSync(join(duck, file), join(pub, "duckdb", file));
}

const atlas = JSON.parse(readFileSync(join(root, "node_modules", "us-atlas", "counties-10m.json"), "utf8"));
const counties = feature(atlas, atlas.objects.counties);
const nj = {
  type: "FeatureCollection",
  features: counties.features
    .filter((f) => String(f.id).startsWith("34"))
    .map((f) => ({ type: "Feature", id: String(f.id), properties: { name: f.properties.name }, geometry: f.geometry })),
};
mkdirSync(join(pub, "data"), { recursive: true });
writeFileSync(join(pub, "data", "nj_counties.json"), JSON.stringify(nj));
console.log(`prepared duckdb bundles and ${nj.features.length} New Jersey counties`);

// Color tokens for both themes, straight from the validated palette.
const palette = JSON.parse(readFileSync(join(root, "src", "theme", "palette.json"), "utf8"));
const block = (mode) => {
  const p = palette[mode];
  const lines = [
    `--surface: ${p.surface};`, `--raised: ${p.raised};`, `--hairline: ${p.hairline};`,
    `--ink: ${p.ink};`, `--ink2: ${p.ink2};`, `--control: ${p.control};`,
    ...p.categorical.map((c, i) => `--cat-${i + 1}: ${c};`),
    ...p.sequential.map((c, i) => `--seq-${i + 1}: ${c};`),
    ...p.ordinal.map((c, i) => `--ord-${i + 1}: ${c};`),
    ...p.diverging.map((c, i) => `--div-${i + 1}: ${c};`),
    ...Object.entries(p.status).map(([k, c]) => `--${k}: ${c};`),
    `color-scheme: ${mode};`,
  ];
  return lines.map((l) => `  ${l}`).join("\n");
};
writeFileSync(
  join(root, "src", "app", "tokens.css"),
  `/* Generated by scripts/prepare-assets.mjs from src/theme/palette.json. Do not edit. */\n` +
    `:root,\n[data-theme="dark"] {\n${block("dark")}\n}\n\n[data-theme="light"] {\n${block("light")}\n}\n`,
);
